defmodule Elixirmachine.Generator.ScriptBuilder do
  @moduledoc false

  alias Elixirmachine.Generations.Generation
  alias Elixirmachine.Generator.{Planner, TemplateRenderer}

  def build(%Generation{} = generation) do
    with {:ok, plan} <- Planner.plan(generation),
         {:ok, files} <- render_templates(plan) do
      script = assemble_script(generation, plan.commands, files)
      {:ok, script, script_filename(generation)}
    end
  end

  defp render_templates(%{context: context, templates: templates}) do
    templates
    |> Enum.reduce_while({:ok, []}, fn {path, template}, {:ok, acc} ->
      case TemplateRenderer.render(template, context) do
        {:ok, content} -> {:cont, {:ok, [{path, content} | acc]}}
        {:error, reason} -> {:halt, {:error, "template #{template}: #{inspect(reason)}"}}
      end
    end)
    |> case do
      {:ok, files} -> {:ok, Enum.reverse(files)}
      other -> other
    end
  end

  defp assemble_script(%{target_os: :macos} = generation, commands, files) do
    [
      "#!/usr/bin/env bash",
      "set -euo pipefail",
      "",
      "# Generated by elixirmachine",
      "# Project: #{generation.project_name}",
      "",
      "command -v mix >/dev/null 2>&1 || { echo \"mix not found on PATH\"; exit 1; }",
      "command -v elixir >/dev/null 2>&1 || { echo \"elixir not found on PATH\"; exit 1; }",
      "command -v docker >/dev/null 2>&1 || echo \"warning: docker not found on PATH\"",
      "",
      "OUTPUT_PATH=\"#{escape_sh(generation.output_path)}\"",
      "mkdir -p \"$OUTPUT_PATH\"",
      "cd \"$OUTPUT_PATH\"",
      "",
      "mix archive.install hex igniter_new --force",
      ""
    ]
    |> Kernel.++(Enum.map(commands, & &1.command))
    |> Kernel.++([""])
    |> Kernel.++(write_files_sh(files))
    |> Kernel.++([
      "",
      "echo \"Done. Next: docker compose up -d && mix setup\""
    ])
    |> Enum.join("\n")
  end

  defp assemble_script(%{target_os: :windows} = generation, commands, files) do
    [
      "@echo off",
      "setlocal EnableExtensions",
      "",
      "REM Generated by elixirmachine",
      "REM Project: #{generation.project_name}",
      "",
      "where mix >nul 2>nul || (echo mix not found on PATH & exit /b 1)",
      "where elixir >nul 2>nul || (echo elixir not found on PATH & exit /b 1)",
      "where docker >nul 2>nul || echo warning: docker not found on PATH",
      "",
      "set \"OUTPUT_PATH=#{generation.output_path}\"",
      "if not exist \"%OUTPUT_PATH%\" mkdir \"%OUTPUT_PATH%\"",
      "cd /d \"%OUTPUT_PATH%\"",
      "",
      "call mix archive.install hex igniter_new --force",
      ""
    ]
    |> Kernel.++(Enum.map(commands, &("call " <> &1.command)))
    |> Kernel.++([""])
    |> Kernel.++(write_files_bat(files))
    |> Kernel.++([
      "",
      "echo Done. Next: docker compose up -d ^&^& mix setup",
      "endlocal"
    ])
    |> Enum.join("\r\n")
  end

  defp write_files_sh(files) do
    Enum.flat_map(files, fn {path, content} ->
      [
        "cat > #{escape_sh(path)} <<'ELIXIRMACHINE_EOF'",
        content,
        "ELIXIRMACHINE_EOF",
        ""
      ]
    end)
  end

  defp write_files_bat(files) do
    Enum.flat_map(files, fn {path, content} ->
      lines = String.split(content, ~r/\r?\n/)

      [
        "if exist #{path} del /q #{path}"
        | Enum.map(lines, fn line ->
            "echo #{bat_escape(line)}>>#{path}"
          end)
      ]
    end)
  end

  defp bat_escape(line) do
    line
    |> String.replace("%", "%%")
    |> String.replace("|", "^|")
    |> String.replace("&", "^&")
    |> String.replace("<", "^<")
    |> String.replace(">", "^>")
  end

  defp escape_sh(value), do: value

  defp script_filename(%{target_os: :macos, project_name: name}), do: "build-#{name}.sh"
  defp script_filename(%{target_os: :windows, project_name: name}), do: "build-#{name}.bat"
end
